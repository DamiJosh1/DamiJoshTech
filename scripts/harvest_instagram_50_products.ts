async function seedHarvestedProducts() {
  console.log(`Starting batch harvest import of ${HARVESTED_50_PRODUCTS.length} products into Firestore database...`);
  let successCount = 0;
  
  for (const item of HARVESTED_50_PRODUCTS) {
    try {
      const docRef = doc(db, 'products', item.id);
      await setDoc(docRef, {
        ...item,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp()
      }, { merge: true });
      successCount++;
      console.log(`[${successCount}/${HARVESTED_50_PRODUCTS.length}] Published: ${item.name} (${item.category} - ₦${item.price.toLocaleString()})`);
    } catch (err) {
      console.error(`Failed to publish product ${item.id}:`, err);
    }
  }

  console.log(`\n🎉 BATCH HARVEST COMPLETED! Successfully inserted ${successCount} products into SAJODA store.`);
  process.exit(0);
}

seedHarvestedProducts().catch((err) => {
  console.error('Fatal harvest error:', err);
  process.exit(1);
});
